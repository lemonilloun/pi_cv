"""Путевая точка политики -> намерение (throttle, steer).

Единственное место, где предсказание превращается в управление. Дальше идёт
существующий путь без изменений: `robocar.mix_drive` (он уже знает про
зеркальную распайку моторов и про приоритет поворота при насыщении) и
`drive_profile.shape` (пороги страгивания). Ни то, ни другое здесь не
повторяется — повторить их значит завести вторую версию, которая разойдётся
с первой на первой же правке железа.

**Системы координат, и это главное.** Политика выдаёт точку в системе
камеры по соглашению ROS: x вперёд, y ВЛЕВО. Панель же шлёт `D -> steer +1`,
то есть у нас положительный steer — это ВПРАВО. Знаки противоположны, и
перепутать их — не абстрактный риск: на этом шасси уже ловилась ровно такая
ошибка (нажимаешь влево, едет вправо), потому что вперёд-назад при
перепутанном знаке выглядит правильно и ошибка прячется до первого поворота.
Соотношение закреплено тестом, а не комментарием.
"""

from __future__ import annotations

import math

# Такт управления. Точка предсказана как смещение за один шаг.
CONTROL_DT_S = 1.0 / 4.0
# Смещение, при котором просится полный ход. Апстрим масштабирует выход
# политики на max_v/rate = 0.2/4, так что один шаг — это порядка 5 см.
FULL_STEP_M = 0.05
# Угол, при котором просится полный поворот. Меньше — поворот пропорционален
# ошибке курса.
FULL_STEER_RAD = math.radians(45.0)
# Ниже этого смещение считается нулевым и в дело идёт предсказанный курс.
EPS_M = 1e-8


def waypoint_to_drive(waypoint, full_step_m: float = FULL_STEP_M,
                      full_steer_rad: float = FULL_STEER_RAD) -> tuple[float, float]:
    """(dx, dy[, hx, hy]) в системе камеры -> (throttle, steer) в [-1, 1].

    **Закон управления НЕ скопирован у апстрима, и это осознанно.** Там
    `v = dx/dt`, `w = atan(dy/dx)/dt` с обрезкой по max_v/max_w — команды
    для регулятора СКОРОСТИ, который на LoCoBot есть. У нас на выходе ШИМ
    без обратной связи: «0.4 рад/с» исполнить нечем, и деление на max_w
    превращает почти любую боковую точку в полный разворот (замерено: точка
    всего в 6° от оси уже насыщает поворот в единицу). Робот на этом
    раскачивается.

    Поэтому здесь пропорциональный закон по ошибке курса: поворот растёт
    линейно до `full_steer_rad`, тяга падает как косинус ошибки. Точка
    сбоку — это в первую очередь поворот, а не езда мимо цели.

    `throttle` неотрицателен: политика обучена вести вперёд, а задний ход по
    предсказанию точки — почти всегда неверно понятый разворот.
    """
    values = list(waypoint)
    if len(values) not in (2, 4):
        raise ValueError(f"Путевая точка должна быть 2- или 4-мерной, получено {len(values)}")
    dx, dy = float(values[0]), float(values[1])

    if abs(dx) < EPS_M and abs(dy) < EPS_M:
        if len(values) != 4:
            return 0.0, 0.0
        # Смещения нет, но есть предсказанный курс — доворачиваем на него.
        heading = _wrap(math.atan2(float(values[3]), float(values[2])))
        return 0.0, _steer_from(heading, full_steer_rad)

    # atan2, а НЕ atan(dy/dx) как в апстриме. Для точки впереди они
    # совпадают тождественно; для точки позади atan теряет квадрант и
    # доворачивает длинной стороной.
    heading = math.atan2(dy, dx)
    distance = math.hypot(dx, dy)

    # Косинус ошибки: строго вперёд — полный ход, вбок — ноль, назад —
    # отрицательный и обрезается в ноль, так что остаётся чистый разворот.
    forward = max(0.0, math.cos(heading))
    throttle = min(1.0, distance / full_step_m) * forward
    return throttle, _steer_from(heading, full_steer_rad)


def _steer_from(heading_rad: float, full_steer_rad: float) -> float:
    """Ошибка курса -> steer. Знак: у политики +угол это влево (ROS,
    против часовой), у нас +steer это вправо (панель шлёт D -> +1)."""
    return -max(-1.0, min(1.0, heading_rad / full_steer_rad))


def _wrap(angle: float) -> float:
    """Угол в (-pi, pi]."""
    return (angle + math.pi) % (2.0 * math.pi) - math.pi


def drive_command(waypoint, speed: int) -> tuple[int, int]:
    """Путевая точка -> пара ШИМ для колёс.

    Порогом страгивания здесь НЕ занимаемся: `RobocarService.drive` уже
    прогоняет пару через `drive_profile.shape` и записывает результат в
    журнал действий. Сделать это ещё и тут значит завести вторую копию
    правила, которая разойдётся с первой при первой же перемерке порогов.
    """
    from mac_server.robocar import mix_drive

    throttle, steer = waypoint_to_drive(waypoint)
    return mix_drive(throttle, steer, speed)
