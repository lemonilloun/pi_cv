"""Математика управления этим шасси: трогание, повороты, удержание курса.

Чистые функции без железа и без сети — их можно проверить тестами, а не
заездом. Физика, из которой всё следует, ниже; подробный разбор в
`docs/drive_control.md`.

**Что за объект.** Два ведущих колеса и ролик, привод разомкнутый: ШИМ
задаётся, скорость не измеряется (энкодеров нет). Единственная обратная связь
в системе — курс с IMU, 100 Гц, дрейф 0.03 град/мин.

**Три беды, и у каждой своя причина.**

1. *Трогание.* У двигателя постоянного тока момент пропорционален току, а
   ток при неподвижном роторе максимален — то есть застрявший мотор берёт
   САМЫЙ большой ток и весь его превращает в тепло. Рампа 8 единиц за 15 мс
   ведёт ШИМ от нуля до 150 за 280 мс, и почти всё это время команда лежит
   ниже порога страгивания. Лечится не плавностью, а наоборот — коротким
   ударом полной мощности, чтобы сорвать трение покоя, после чего держать
   можно меньшим.

2. *Разворот на месте.* Оба колеса скребут вбок, ролик упирается. Момент
   сопротивления здесь кратно больше, чем при качении, и на потяжелевшем
   шасси его не хватает. Дуга вместо пивота переводит скольжение в качение
   и обходится в разы дешевле — поэтому поворот с места автоматически
   получает продольную составляющую.

3. *Увод с прямой.* Вес распределён неравномерно, колёса не идентичны.
   Разомкнутый контур этого исправить не может в принципе: он не знает, куда
   робот едет. Нужна обратная связь по курсу — ПИ-регулятор ниже.
"""

from __future__ import annotations

import math
from dataclasses import dataclass, field

# --------------------------------------------------------------- привод

# Отображение запроса в ШИМ мотора, как в прошивке:
#   pwm = map(|request|, 5..255, MIN_PWM..MAX_PWM)
# Держим здесь же, чтобы рассуждать в единицах МОТОРА, а не запроса: «160»
# ничего не значит, пока не сказано, во что оно превращается.
ESP_MIN_PWM = 40
ESP_MAX_PWM = 150


def motor_pwm(request: int, min_pwm: int = ESP_MIN_PWM,
              max_pwm: int = ESP_MAX_PWM) -> int:
    """Во что прошивка превратит запрос. Знак сохраняется."""
    magnitude = min(255, abs(int(request)))
    if magnitude == 0:
        return 0
    scaled = min_pwm + (magnitude - 5) * (max_pwm - min_pwm) / 250.0
    value = int(round(min(max(scaled, min_pwm), max_pwm)))
    return value if request >= 0 else -value


def request_for_motor_pwm(pwm: int, min_pwm: int = ESP_MIN_PWM,
                          max_pwm: int = ESP_MAX_PWM) -> int:
    """Обратное отображение: какой запрос даст этот ШИМ на моторе.

    Нужно, чтобы задавать величины в физических единицах — «хочу 80% мощности
    на моторе» — а не подбирать число запроса вслепую.
    """
    magnitude = min(max(abs(int(pwm)), min_pwm), max_pwm)
    request = 5 + (magnitude - min_pwm) * 250.0 / max(1, max_pwm - min_pwm)
    value = int(round(min(255, max(5, request))))
    return value if pwm >= 0 else -value


# ------------------------------------------------------------- повороты

# Доля скорости, которая остаётся ВНУТРЕННЕМУ колесу в самой крутой дуге.
# Ноль означал бы остановленное колесо, а обесточенный редукторный мотор не
# катится свободно, он сопротивляется — то есть превращается в тормоз,
# который второе колесо вынуждено таскать. Отсюда четверть, а не ноль.
INNER_WHEEL_RATIO = 0.25
# Ниже этого запроса руля считаем, что поворот не запрашивали.
STEER_EPS = 1e-6


def arc_turn(throttle: float, steer: float,
             assist: float = INNER_WHEEL_RATIO) -> tuple[float, float]:
    """Превратить запрос поворота с места в ДУГУ.

    Разворот на месте на этом шасси недостижим при любой доступной скорости:
    оба колеса скребут вбок, ролик упирается, и момента не хватает. Дуга
    переводит скольжение в качение и обходится в разы дешевле.

    Наивная попытка — «добавить газу к повороту» — здесь не работает, и это
    проверено замером. В микшере стоит приоритет поворота при насыщении: он
    сохраняет РАЗНОСТЬ колёс и сдвигает пару целиком, то есть выкидывает
    ровно ту общую составляющую, которую добавка и создавала. Поэтому дуга
    задаётся не добавкой, а формой: внешнее колесо на полную, внутреннее —
    долей от него, и доля тем меньше, чем круче запрошен поворот.

    Возвращается пара (throttle, steer), которую микшер уже не насыщает, —
    их сумма по построению не превышает единицы.

    Это ИЗМЕНЕНИЕ ПОВЕДЕНИЯ: нажатие «влево» на стоящем роботе теперь трогает
    его с места. Так и задумано — иначе он не поворачивает вовсе. Настоящий
    пивот остаётся доступен через `assist=0.0`; им пользуется обзорный спин,
    которому нужно как раз не ехать.
    """
    magnitude = abs(steer)
    if magnitude < STEER_EPS:
        return throttle, steer
    if assist <= 0.0:
        return throttle, steer                    # честный разворот на месте
    # Робот уже едет — этот случай работает и без нас, не трогаем.
    if abs(throttle) > STEER_EPS:
        return throttle, steer

    magnitude = min(1.0, magnitude)
    # Крутизна задаёт, насколько отстаёт внутреннее колесо: чуть тронул руль —
    # колёса почти равны и робот просто подруливает на ходу.
    inner = 1.0 - (1.0 - assist) * magnitude
    forward = (1.0 + inner) / 2.0
    difference = (1.0 - inner) / 2.0
    return forward, math.copysign(difference, steer)


# ------------------------------------------------------------- трогание


@dataclass
class KickStart:
    """Короткий удар полной мощности, чтобы сорвать трение покоя.

    Рампа существует, чтобы не рвать шестерни и просадку питания. Но при
    трогании она работает против физики: команда ползёт через зону, где
    момента не хватает, а ток уже максимальный. Удар решает обратную задачу —
    проскочить эту зону как можно быстрее.

    Состояние минимально: нужен только момент начала удара и то, стояли ли
    колёса до него.
    """

    pwm: int = 255            # запрос на время удара (уйдёт в MAX_PWM мотора)
    duration_s: float = 0.12  # дольше — рывок и просадка питания
    cooldown_s: float = 0.5   # не бить повторно, пока робот уже едет
    _started_at: float | None = field(default=None, repr=False)
    _last_kick_at: float = field(default=-1e9, repr=False)

    def request(self, current: tuple[int, int], target: tuple[int, int],
                now: float) -> tuple[int, int] | None:
        """Что послать на колёса ВМЕСТО цели, либо None — послать цель.

        Удар нужен в двух случаях, и оба про переход через ноль скорости:
        трогание с места и реверс. Плавный переход через ноль — это проход
        через зону застревания дважды.
        """
        if self._started_at is not None:
            if now - self._started_at < self.duration_s:
                return self._shaped(target)
            self._started_at = None
            return None

        if target == (0, 0):
            return None
        if now - self._last_kick_at < self.cooldown_s:
            return None
        if not self._needs_kick(current, target):
            return None

        self._started_at = now
        self._last_kick_at = now
        return self._shaped(target)

    def _needs_kick(self, current: tuple[int, int],
                    target: tuple[int, int]) -> bool:
        for cur, tgt in zip(current, target):
            if tgt == 0:
                continue
            if cur == 0:                       # трогание
                return True
            if (cur > 0) != (tgt > 0):         # реверс
                return True
        return False

    def _shaped(self, target: tuple[int, int]) -> tuple[int, int]:
        """Удар сохраняет НАПРАВЛЕНИЕ каждого колеса и соотношение сторон.

        Бить обоими колёсами одинаково значило бы на время удара поехать
        прямо вместо поворота — как раз в тот момент, когда поворот и
        начинается.
        """
        peak = max(abs(target[0]), abs(target[1])) or 1
        return tuple(  # type: ignore[return-value]
            0 if value == 0 else int(round(math.copysign(
                self.pwm * abs(value) / peak, value)))
            for value in target
        )


# --------------------------------------------------- удержание курса


def wrap_deg(angle: float) -> float:
    """Угол в (-180, 180]. Без этого регулятор на переходе через 0/360
    получает ошибку в 359 градусов и выкручивает руль в противоположную
    сторону."""
    return (angle + 180.0) % 360.0 - 180.0


@dataclass
class HeadingHold:
    """ПИ-регулятор курса: держит прямую, пока оператор не поворачивает.

    Почему ПИ, а не П. Увод здесь ПОСТОЯННЫЙ — его создаёт несимметричный
    вес и разные колёса, а не случайный шум. Чисто пропорциональный регулятор
    против постоянного возмущения всегда оставляет статическую ошибку: он
    выдаёт поправку, только пока есть отклонение. Интегральная часть
    накапливает ровно ту постоянную поправку, которая нужна, и уводит ошибку
    в ноль. По сути она сама измеряет несимметрию шасси, которую иначе
    пришлось бы подбирать руками.

    Почему не Д. Дифференциальная часть усиливает шум измерения, а курс тут
    приходит с квантованием и на 100 Гц; выигрыш от неё на таком медленном
    объекте меньше, чем вносимая дрожь.

    **Антинакопление обязательно.** Если поправка уже упёрлась в предел, а
    ошибка сохраняется, интеграл продолжает расти и потом отрабатывает
    назад с огромным перелётом. Поэтому интегрируем только когда выход не
    насыщен.

    **Пока оператор рулит, уставка следует за измерением.** Иначе регулятор
    считает намеренный поворот ошибкой и борется с рулём; а на отпускании
    накопленный интеграл швыряет робота обратно.
    """

    kp: float = 0.020         # доля руля на градус ошибки
    ki: float = 0.006         # доля руля на градус-секунду
    max_correction: float = 0.45
    max_integral: float = 60.0    # градус-секунды
    # +1, если рост показаний курса означает поворот ВЛЕВО (правая тройка
    # осей, вращение против часовой). **Знак на этом стенде не проверен** —
    # так и записано в CLAUDE.md, и калибровка по гравитации определить его
    # физически не может: вращение вокруг вертикали не меняет вектор силы
    # тяжести. Ошибка в знаке превращает обратную связь из отрицательной в
    # ПОЛОЖИТЕЛЬНУЮ: вместо выправления регулятор усиливает увод и робота
    # закручивает. Отсюда и сторож расхождения ниже — он ловит именно это,
    # не дожидаясь, пока кто-нибудь заметит глазами.
    yaw_sign: float = 1.0
    # Ошибка, выше которой удержание объявляется несостоятельным. Прямая,
    # ушедшая на 40 градусов при работающем регуляторе, — это не ветер.
    divergence_deg: float = 40.0
    setpoint: float | None = None
    integral: float = 0.0
    diverged: bool = False
    _last_t: float | None = field(default=None, repr=False)

    def reset(self, heading_deg: float | None = None) -> None:
        self.setpoint = heading_deg
        self.integral = 0.0
        self.diverged = False
        self._last_t = None

    def update(self, heading_deg: float | None, steer_cmd: float,
               now: float, moving: bool = True) -> float:
        """Вернуть скорректированный руль.

        `heading_deg` None (IMU молчит) — возвращаем команду как есть:
        регулятор без измерения обязан самоустраниться, а не держать
        последнюю поправку. Замерший курс неотличим от ровного хода, и
        именно так однажды уже пряталась поломка связи с датчиком.
        """
        dt = 0.0 if self._last_t is None else max(0.0, now - self._last_t)
        self._last_t = now

        if heading_deg is None or self.diverged:
            return steer_cmd
        heading_deg = self.yaw_sign * heading_deg

        # Оператор рулит или робот стоит — держать нечего, уставка едет за
        # измерением, интеграл не копится.
        if steer_cmd != 0.0 or not moving:
            self.setpoint = heading_deg
            self.integral = 0.0
            return steer_cmd

        if self.setpoint is None:
            self.setpoint = heading_deg
            return steer_cmd

        error = wrap_deg(self.setpoint - heading_deg)
        if abs(error) > self.divergence_deg:
            # Скорее всего перевёрнут знак курса. Самоустраняемся и говорим
            # об этом, а не продолжаем крутить руль в сторону увода.
            self.diverged = True
            self.integral = 0.0
            return steer_cmd
        proportional = self.kp * error
        candidate = proportional + self.ki * (self.integral + error * dt)

        # Интегрируем только вне насыщения — иначе накопленное придётся долго
        # отрабатывать назад.
        if abs(candidate) < self.max_correction:
            self.integral = max(-self.max_integral,
                                min(self.max_integral, self.integral + error * dt))

        correction = proportional + self.ki * self.integral
        correction = max(-self.max_correction, min(self.max_correction, correction))
        # Ошибка «курс больше уставки» означает, что робота увело влево;
        # выправлять надо вправо, а вправо у нас положительный руль.
        return max(-1.0, min(1.0, steer_cmd - correction))
